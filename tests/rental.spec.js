import { test, expect } from '@playwright/test'

test('real MySQL: customer registration, admin fleet, booking, cancellation and logout', async ({ page, browser }) => {
  await page.goto('/admin/dashboard')
  await expect(page).toHaveURL(/\/login$/)
  await page.getByRole('link', { name: 'Create an account' }).click()
  await page.getByLabel('Full name').fill('Browser Test Customer')
  await page.getByLabel('Phone number').fill('0779876543')
  await page.getByLabel('Email', { exact: true }).fill('customer@example.com')
  await page.getByLabel('Password', { exact: true }).fill('browser-test-password')
  await page.getByLabel('Confirm password').fill('browser-test-password')
  await page.getByRole('button', { name: 'Register', exact: true }).click()
  await expect(page).toHaveURL(/\/customer\/dashboard$/)
  await expect(page.getByRole('heading', { name: 'Welcome, Browser Test Customer' })).toBeVisible()
  await page.goto('/admin/vehicles')
  await expect(page).toHaveURL(/\/customer\/dashboard$/)
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Welcome, Browser Test Customer' })).toBeVisible()

  const adminContext = await browser.newContext()
  const admin = await adminContext.newPage()
  await admin.goto('http://127.0.0.1:5174/login')
  await admin.getByLabel('Email', { exact: true }).fill('admin@example.com')
  await admin.getByLabel('Password', { exact: true }).fill('browser-test-password')
  await admin.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(admin).toHaveURL(/\/admin\/dashboard$/)
  await admin.getByRole('link', { name: 'Manage fleet', exact: true }).click()
  await admin.getByRole('button', { name: 'Add vehicle', exact: true }).click()
  for (const [label, value] of Object.entries({ 'Vehicle name': 'Test Corolla', Brand: 'Toyota', Model: 'Corolla',
    'Manufacturing year': '2025', 'Registration number': 'TEST-100', Category: 'Sedan', Transmission: 'Automatic',
    'Fuel type': 'Petrol', 'Number of seats': '5', 'Price per day (Rs.)': '2500', 'Mileage (km)': '1000', Color: 'White' })) {
    await admin.getByLabel(label, { exact: true }).fill(value)
  }
  await admin.getByLabel('Original vehicle image').selectOption({ label: 'Toyota Corolla.jpg' })
  await admin.getByRole('button', { name: 'Save vehicle' }).click()
  await expect(admin.getByRole('cell', { name: 'TEST-100', exact: true })).toBeVisible()
  await expect(admin.getByRole('img', { name: 'Test Corolla' })).toBeVisible()

  const guestContext = await browser.newContext()
  const guest = await guestContext.newPage()
  await guest.goto('http://127.0.0.1:5174/vehicles')
  await guest.getByRole('link', { name: 'View Details' }).click()
  await expect(guest.getByRole('heading', { name: 'Toyota Corolla' })).toBeVisible()
  await expect.poll(() => guest.getByRole('img', { name: 'Toyota Corolla' }).evaluate(image => image.naturalWidth)).toBeGreaterThan(0)
  await guest.getByRole('link', { name: 'Rent This Vehicle' }).click()
  await expect(guest).toHaveURL(/\/login$/)
  await guest.getByLabel('Email', { exact: true }).fill('customer@example.com')
  await guest.getByLabel('Password', { exact: true }).fill('browser-test-password')
  await guest.getByRole('button', { name: 'Log in', exact: true }).click()
  await expect(guest).toHaveURL(/\/booking\/\d+$/)
  await guestContext.close()

  await page.getByRole('link', { name: 'Vehicles', exact: true }).click()
  await expect(page.getByRole('img', { name: 'Toyota Corolla' })).toBeVisible()
  await page.getByRole('link', { name: 'Rent Now' }).click()
  const date = (days) => { const value = new Date(); value.setUTCDate(value.getUTCDate() + days); return value.toISOString().slice(0, 10) }
  await page.getByLabel('Pickup date').fill(date(2))
  await page.getByLabel('Return date').fill(date(5))
  await page.getByRole('button', { name: 'Check availability and price' }).click()
  await expect(page.getByText('Rs. 7500.00', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Submit booking request' }).click()
  await expect(page).toHaveURL(/\/my-bookings$/)
  await expect(page.getByText('pending', { exact: true }).last()).toBeVisible()
  await admin.getByRole('link', { name: 'Bookings', exact: true }).click()
  await admin.getByRole('button', { name: 'Confirm', exact: true }).click()
  await expect(admin.getByText('confirmed', { exact: true }).last()).toBeVisible()
  await page.reload()
  await expect(page.getByText('confirmed', { exact: true }).last()).toBeVisible()
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: 'Cancel booking', exact: true }).click()
  await expect(page.getByText('cancelled', { exact: true }).last()).toBeVisible()
  await page.getByRole('link', { name: 'Profile', exact: true }).click()
  await page.getByLabel('Full name', { exact: true }).fill('Updated Customer')
  await page.getByRole('button', { name: 'Save profile' }).click()
  await expect(page.getByRole('status')).toHaveText('Profile updated.')
  await page.getByRole('button', { name: 'Log out', exact: true }).click()
  await expect(page).toHaveURL(/\/login$/)
  await page.goto('/my-bookings')
  await expect(page).toHaveURL(/\/login$/)
  await adminContext.close()
})
